def validate_specs(
    specs: Sequence[PatternSpec],
    input_midi: Path,
    slot_maps: Dict[str, SlotMapDefinition],
    bars: Sequence[BarInfo],
    events: Sequence[AbsoluteEvent],
) -> List[PatternSpec]:
    selected = [spec for spec in specs if spec.export]
    if not selected:
        fail("CSV has no EXPORT=YES rows")

    names: Set[str] = set()
    expected_file = input_midi.name.casefold()
    for spec in selected:
        if Path(spec.file).name.casefold() != expected_file:
            fail(
                f"CSV row {spec.row_number}: FILE={spec.file!r} does not match input MIDI {input_midi.name!r}"
            )
        if spec.name in names:
            fail(f"CSV row {spec.row_number}: duplicate NAME {spec.name}")
        names.add(spec.name)
        if spec.slot_map not in slot_maps:
            fail(f"CSV row {spec.row_number}: unknown SLOT_MAP {spec.slot_map!r}")
        if spec.end_bar > len(bars):
            fail(
                f"CSV row {spec.row_number}: bar range {spec.start_bar}-{spec.end_bar} exceeds MIDI bar count {len(bars)}"
            )
        start_bar = bars[spec.start_bar - 1]
        end_bar = bars[spec.end_bar - 1]
        actual_ts_values = {(bar.numerator, bar.denominator) for bar in bars[spec.start_bar - 1 : spec.end_bar]}
        csv_ts = parse_time_signature(spec.time_sig, row_number=spec.row_number)
        if len(actual_ts_values) != 1 or csv_ts not in actual_ts_values:
            actual_text = "→".join(f"{bar.numerator}/{bar.denominator}" for bar in bars[spec.start_bar - 1 : spec.end_bar])
            fail(
                f"CSV row {spec.row_number}: TIME_SIG={spec.time_sig} does not match bars {spec.start_bar}-{spec.end_bar} ({actual_text})"
            )
        expected_source = f"{input_midi.name}:{spec.start_bar}-{spec.end_bar}"
        if spec.source != expected_source:
            fail(
                f"CSV row {spec.row_number}: SOURCE={spec.source!r}; expected {expected_source!r}"
            )
        hits = drum_note_ons(events, start_bar.start_tick, end_bar.end_tick)
        if not hits:
            fail(f"CSV row {spec.row_number}: no CH10 drum note_on events in selected range")
        notes = {int(event.message.note) for event in hits if isinstance(event.message, Message)}
        missing = sorted(notes - slot_maps[spec.slot_map].accepted_notes)
        if missing:
            fail(
                f"CSV row {spec.row_number}: SLOT_MAP {spec.slot_map} does not accept MIDI note(s) {missing}"
            )

    return selected


