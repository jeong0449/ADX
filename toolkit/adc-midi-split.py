@dataclass(frozen=True)
class SlotDefinition:
    index: int
    abbrev: str
    extended: str
    representative_midi: int
    allowed_notes: Tuple[int, ...]


@dataclass(frozen=True)
class SlotMapDefinition:
    map_id: int
    name: str
    slots: Tuple[SlotDefinition, ...]

    @property
    def accepted_notes(self) -> Set[int]:
        out: Set[int] = set()
        for slot in self.slots:
            out.update(slot.allowed_notes)
        return out

    def slot_for_note(self, note: int) -> Optional[int]:
        for slot in self.slots:
            if note in slot.allowed_notes:
                return slot.index
        return None


@dataclass(frozen=True)
class PatternSpec:
    row_number: int
    file: str
    start_bar: int
    end_bar: int
    name: str
    time_sig: str
    slot_map: str
    export: bool
    genre: str
    subdiv: str
    orn: bool
    duplicate_of: str
    source: str


@dataclass(frozen=True)
class BarInfo:
    number: int
    start_tick: int
    end_tick: int
    numerator: int
    denominator: int


@dataclass(frozen=True)
class AbsoluteEvent:
    tick: int
    order: int
    message: Message | MetaMessage


