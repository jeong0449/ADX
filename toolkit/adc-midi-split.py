def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog=SCRIPT_NAME,
        description="Split PatternLab-selected CH10 MIDI ranges and/or create an A4 2-column PDF catalog.",
    )
    parser.add_argument("input_midi", type=Path, help="Original MIDI file (SMF Type 0 or 1)")
    parser.add_argument("pattern_csv", type=Path, help="CSV downloaded from ADC PatternLab")
    parser.add_argument("--split", action="store_true", help="Save one NAME.MID file per EXPORT=YES row")
    parser.add_argument("--pdf", action="store_true", help="Create a multi-page A4 pattern-grid PDF")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Directory for split MIDI files (default: <CSV directory>/split-midi)",
    )
    parser.add_argument(
        "--pdf-output",
        type=Path,
        default=None,
        help="PDF output path (default: <CSV directory>/<MIDI stem>_patterns.pdf)",
    )
    parser.add_argument(
        "--slot-maps",
        type=Path,
        default=None,
        help="slot_map_definitions.json (default: beside this script)",
    )
    parser.add_argument("--overwrite", action="store_true", help="Overwrite existing outputs")
    parser.add_argument("--keep-png", action="store_true", help="Keep per-pattern grid PNG files beside the PDF")
    parser.add_argument("--no-ghostscript", action="store_true", help="Do not run Ghostscript even if found")
    parser.add_argument("--dry-run", action="store_true", help="Validate and print the plan without writing files")
    parser.add_argument("--version", action="version", version=VERSION_TEXT)
    args = parser.parse_args(argv)
    if not args.split and not args.pdf:
        parser.error("select at least one output: --split and/or --pdf")
    return args


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    if not args.input_midi.is_file():
        fail(f"MIDI file not found: {args.input_midi}")
    if not args.pattern_csv.is_file():
        fail(f"CSV file not found: {args.pattern_csv}")

    slot_map_path = args.slot_maps or Path(__file__).with_name("slot_map_definitions.json")
    slot_maps = load_slot_maps(slot_map_path)
    specs = load_pattern_csv(args.pattern_csv)

    try:
        mid = MidiFile(str(args.input_midi))
    except Exception as exc:
        fail(f"cannot read MIDI {args.input_midi}: {exc}")
    if mid.type not in (0, 1):
        fail(f"only SMF Type 0 or 1 is supported, got Type {mid.type}")

    events = merged_absolute_events(mid)
    total_tick = max((event.tick for event in events), default=0)
    bars = build_bar_map(mid.ticks_per_beat, collect_time_signatures(events), total_tick)
    selected = validate_specs(specs, args.input_midi, slot_maps, bars, events)

    output_dir = args.output_dir or args.pattern_csv.parent / "split-midi"
    pdf_output = args.pdf_output or args.pattern_csv.parent / f"{safe_output_stem(args.input_midi.stem)}_patterns.pdf"

    print(VERSION_TEXT)
    print(f"[OK] MIDI       : {args.input_midi}")
    print(f"[OK] CSV        : {args.pattern_csv}")
    print(f"[OK] SLOT_MAPS  : {slot_map_path}")
    print(f"[OK] MIDI type  : {mid.type}")
    print(f"[OK] TPQ        : {mid.ticks_per_beat}")
    print(f"[OK] bars       : {len(bars)}")
    print(f"[OK] export rows: {len(selected)}")

    if args.split:
        print(f"[PLAN] split MIDI -> {output_dir}")
        for spec in selected:
            print(f"       {spec.name}.MID <- bars {spec.start_bar}-{spec.end_bar}")
    if args.pdf:
        print(f"[PLAN] PDF -> {pdf_output}")

    if args.dry_run:
        print("[DRY RUN] Validation completed; no files were written.")
        return 0

    split_count = 0
    if args.split:
        output_dir.mkdir(parents=True, exist_ok=True)
        conflicts = [output_dir / f"{spec.name}.MID" for spec in selected if (output_dir / f"{spec.name}.MID").exists()]
        if conflicts and not args.overwrite:
            fail(f"split MIDI output already exists: {conflicts[0]} (use --overwrite)")
        for spec in selected:
            output_path = output_dir / f"{spec.name}.MID"
            save_segment_midi(spec, output_path, mid, bars, events)
            split_count += 1
            print(f"[SPLIT] {output_path.name} <- bars {spec.start_bar}-{spec.end_bar}")

    pdf_pages = 0
    if args.pdf:
        pdf_pages = create_pdf_catalog(
            selected,
            slot_maps,
            bars,
            events,
            args.input_midi,
            mid.ticks_per_beat,
            pdf_output,
            keep_png=args.keep_png,
            no_ghostscript=args.no_ghostscript,
            overwrite=args.overwrite,
        )
        print(f"[PDF] {pdf_output} <- {len(selected)} patterns, {pdf_pages} page(s)")

    print(f"[DONE] split MIDI: {split_count}")
    print(f"[DONE] PDF pages : {pdf_pages}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
