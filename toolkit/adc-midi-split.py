"""adc-midi-split.py 260801f

Split selected drum-pattern ranges from an original MIDI file according to an
ADC PatternLab CSV, and/or create an A4 portrait 2-column x 5-row PDF catalog.

Inputs
------
1. Original MIDI file (SMF Type 0 or 1)
2. PatternLab CSV generated by adc-patternlab.py
3. slot_map_definitions.json (default: beside this script)

Outputs are selected independently:
    --split   Save one CH10 MIDI file per EXPORT=YES row.
    --pdf     Create a multi-page pattern-grid PDF for EXPORT=YES rows.

The script performs no genre, subdivision, name, duplicate, or slot-map
inference. Those decisions are taken directly from the reviewed CSV.
"""

