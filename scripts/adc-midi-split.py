@dataclass(frozen=True)
class AccentLevel:
    index: int
    name: str
    min_velocity: int
    max_velocity: int
    color: Tuple[int, int, int]


@dataclass(frozen=True)
class AccentScheme:
    name: str
    levels: Tuple[AccentLevel, ...]

    @property
    def colors(self) -> Dict[int, Tuple[int, int, int]]:
        return {level.index: level.color for level in self.levels}

    def level_for_velocity(self, velocity: int) -> int:
        for level in self.levels:
            if level.min_velocity <= velocity <= level.max_velocity:
                return level.index
        fail(f"velocity {velocity} is not covered by accent scheme {self.name!r}")


@dataclass(frozen=True)
class SlotDefinition:
    index: int
    abbrev: str
    extended: str
    representative_midi: int
    allowed_notes: Tuple[int, ...]


@dataclass(frozen=True)
class SlotMapDefinition:
    map_id: int
    name: str
    slots: Tuple[SlotDefinition, ...]

    @property
    def accepted_notes(self) -> Set[int]:
        out: Set[int] = set()
        for slot in self.slots:
            out.update(slot.allowed_notes)
        return out

    def slot_for_note(self, note: int) -> Optional[int]:
        for slot in self.slots:
            if note in slot.allowed_notes:
                return slot.index
        return None


@dataclass(frozen=True)
class PatternSpec:
    row_number: int
    file: str
    start_bar: int
    end_bar: int
    name: str
    time_sig: str
    slot_map: str
    export: bool
    genre: str
    subdiv: str
    orn: bool
    duplicate_of: str
    source: str


@dataclass(frozen=True)
class BarInfo:
    number: int
    start_tick: int
    end_tick: int
    numerator: int
    denominator: int


@dataclass(frozen=True)
class AbsoluteEvent:
    tick: int
    order: int
    message: Message | MetaMessage


