def load_pattern_csv(path: Path) -> List[PatternSpec]:
    try:
        handle = path.open("r", encoding="utf-8-sig", newline="")
    except OSError as exc:
        fail(f"cannot open CSV {path}: {exc}")

    with handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            fail(f"CSV has no header: {path}")
        normalized_fields = [str(field).strip().upper() for field in reader.fieldnames]
        missing = sorted(REQUIRED_COLUMNS - set(normalized_fields))
        if missing:
            fail(f"CSV missing required column(s): {', '.join(missing)}")
        reader.fieldnames = normalized_fields

        specs: List[PatternSpec] = []
        for row_number, raw in enumerate(reader, start=2):
            if raw is None or not any(str(v or "").strip() for v in raw.values()):
                continue
            row = {str(k).strip().upper(): str(v or "").strip() for k, v in raw.items() if k is not None}
            try:
                start_bar = int(row.get("START_BAR", ""))
                end_bar = int(row.get("END_BAR", ""))
            except ValueError:
                fail(f"CSV row {row_number}: START_BAR and END_BAR must be integers")
            if start_bar < 1 or end_bar < start_bar:
                fail(f"CSV row {row_number}: invalid bar range {start_bar}-{end_bar}")

            export = parse_yes_no(row.get("EXPORT", ""), field="EXPORT", row_number=row_number)

            name = row.get("NAME", "").upper()
            if export:
                if not NAME_RE.fullmatch(name):
                    fail(
                        f"CSV row {row_number}: NAME must match ABC_0001 "
                        f"for EXPORT=YES, got {name!r}"
                    )
            elif name and not NAME_RE.fullmatch(name):
                fail(
                    f"CSV row {row_number}: non-empty NAME must match ABC_0001, "
                    f"got {name!r}"
                )

            time_sig = row.get("TIME_SIG", "")
            parse_time_signature(time_sig, row_number=row_number)

            subdiv = row.get("SUBDIV", "").upper()
            if subdiv not in VALID_SUBDIV:
                fail(f"CSV row {row_number}: SUBDIV must be one of 16, 32, 8T, 16T, got {subdiv!r}")

            orn_raw = row.get("ORN", "NO") or "NO"
            orn = parse_yes_no(orn_raw, field="ORN", row_number=row_number)

            specs.append(
                PatternSpec(
                    row_number=row_number,
                    file=row.get("FILE", ""),
                    start_bar=start_bar,
                    end_bar=end_bar,
                    name=name,
                    time_sig=time_sig,
                    slot_map=row.get("SLOT_MAP", ""),
                    export=export,
                    genre=row.get("GENRE", "").upper(),
                    subdiv=subdiv,
                    orn=orn,
                    duplicate_of=row.get("DUPLICATE_OF", ""),
                    source=row.get("SOURCE", ""),
                )
            )

    if not specs:
        fail("CSV contains no pattern rows")
    return specs


